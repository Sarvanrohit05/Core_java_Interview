	package com.in.collection;
	
	public class AutoBoxingUnboxing {
		
		public static void main(String[] args) {
			
			//Autoboxing
			//convert an primitive data into object
			 int a = 1 ;
			 Integer b = a ; 
			 System.out.println(b);
			 
			 //inboxing
			  Integer c = 3 ; 
			 int d = c ;
			 System.out.println(d);
			 
		}
	
	}
